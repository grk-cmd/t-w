/* sim-no-attribution.js — 커밋 메시지 · PR 본문에 Claude 표기가 없는가
   실행:  node checks/run.js sim-no-attribution        (판정 함수 mutation test 만)
          node checks/sim-no-attribution.js --body-env PR_BODY --commits-z <파일>
            (CI pr-title 잡이 PR 본문(환경 변수 이름)과 커밋 목록을 넘겨 판정 — 파일은 `git log -z --format='%H%n%B'` 출력)
   ★ 커밋은 이 PR 이 새로 들이는 것만 본다 — main · admin · release/* 에 이미 있는 커밋은 빼고 넘긴다(pr-title.yml).
     main → admin 같은 합쳐 받기 PR 에는 이미 머지된 옛 커밋 수백 개가 따라오는데, 그건 고칠 수 없고 이 PR 이 들인 것도 아니다.
   ★ 왜 — 두 저장소 다 CLAUDE.md · docs/GIT_CONVENTION.md 에 «Claude 표기를 넣지 않는다» 가 적혀 있는데도,
     도구의 기본 안내가 꼬리말을 붙이라고 해서 세션이 계속 넣었다(11-27 #1165). 글로 적은 규칙을 검사로 옮겼다.
   걸리는 것(대소문자 무시):
     · 줄 맨 앞의 `Co-Authored-By:` 가 Claude 나 noreply@anthropic.com 을 가리킴
     · Generated with/by [Claude Code] · 🤖 Generated
     · claude.ai/code 세션 링크
   안 걸리는 것: `.claude/` 경로 · CLAUDE.md · 글 속의 «Claude» 낱말 · 백틱으로 감싼 것(규칙을 설명하는 글).
   서버 저장소(t-w-server)의 deploy/no-attribution.sh 도 같은 규칙이다(줄 단위 — 한 줄을 넘는 꼴은 안 본다) — 하나를 고치면 다른 쪽도. */
'use strict';
const fs = require('fs');
let pass = 0, fail = 0;
const say = (s) => console.log(s);
const chk = (ok, msg) => { ok ? pass++ : fail++; say('  ' + (ok ? '✓' : '✗') + ' ' + msg); };

const RULES = [
  ['Co-Authored-By: Claude', /^[ \t]*co-authored-by:.*(claude|noreply@anthropic\.com)/im],
  ['Generated with Claude Code', /generated[ \t]+(with|by)[ \t]+\[?claude[ \t]+code/i],
  ['🤖 Generated', /🤖[ \t]*generated/i],
  ['claude.ai/code 링크', /claude\.ai\/code/i],
];

/** 글에서 걸린 규칙 이름 목록 — 백틱 안은 설명이라 뺀다 */
function findAttribution(text){
  const plain = String(text || '').replace(/```[\s\S]*?```/g, ' ').replace(/`[^`\n]*`/g, ' ');
  return RULES.filter(([, re]) => re.test(plain)).map(([name]) => name);
}

/** `git log -z --format='%H%n%B'` 출력 → [{ sha, message }] */
function parseGitLogZ(text){
  return String(text || '').split('\0').map((r) => r.replace(/^\n+/, '')).filter((r) => r.trim()).map((r) => {
    const nl = r.indexOf('\n');
    return nl < 0 ? { sha: r, message: '' } : { sha: r.slice(0, nl), message: r.slice(nl + 1) };
  });
}

const bi = process.argv.indexOf('--body-env');
const ci = process.argv.indexOf('--commits-z');
if(bi >= 0 || ci >= 0){
  const body = bi >= 0 ? (process.env[process.argv[bi + 1]] || '') : '';
  const commits = ci >= 0 ? parseGitLogZ(fs.readFileSync(process.argv[ci + 1], 'utf8')) : [];
  say(`PR 본문 1 · 새 커밋 ${commits.length}`);
  const hb = findAttribution(body);
  chk(hb.length === 0, 'PR 본문에 Claude 표기 없음' + (hb.length ? ` — ${hb.join(' · ')} (PR 본문을 고치면 다시 돈다)` : ''));
  for(const c of commits){
    const h = findAttribution(c.message);
    chk(h.length === 0, `커밋 ${String(c.sha).slice(0, 8)} ${String(c.message).split('\n')[0]}` + (h.length ? ` — ${h.join(' · ')}` : ''));
  }
  if(fail) say('  고치는 법: docs/GIT_CONVENTION.md 3장 «Claude 표기» — 커밋은 같은 트리를 새 브랜치에 깨끗한 메시지로 다시 만들어 새 PR(git commit-tree)');
  say(`통과 ${pass} · 실패 ${fail}`);
  process.exit(fail ? 1 : 0);
}

say('mutation test — Claude 표기 판정');
const cases = [
  ['fix(x): 고침\n\n- a.js: 내용\n\nCo-Authored-By: Claude Opus 4.5 <noreply@anthropic.com>', ['Co-Authored-By: Claude']],
  ['fix(x): 고침\n\nco-authored-by: claude <x@y.z>', ['Co-Authored-By: Claude']],
  ['fix(x): 고침\n\n  Co-authored-by: Bot <noreply@anthropic.com>', ['Co-Authored-By: Claude']],
  ['## 무엇을\n고침\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)', ['Generated with Claude Code', '🤖 Generated']],
  ['본문\n\nGenerated with Claude Code', ['Generated with Claude Code']],
  ['본문\n\nGenerated by [Claude Code](https://claude.com/claude-code)', ['Generated with Claude Code']],
  ['본문\n🤖 generated', ['🤖 Generated']],
  ['본문\n\nhttps://claude.ai/code/session_01AbCdEf', ['claude.ai/code 링크']],
  ['본문\nCLAUDE.AI/CODE/session_x', ['claude.ai/code 링크']],
  // 안 걸리는 것
  ['chore(harness): .claude/hooks/risk.py 고침', []],
  ['docs: Claude 표기를 넣지 않는다', []],
  ['docs(CLAUDE.md): 안내 한 줄', []],
  ['- CLAUDE.md: `Co-Authored-By: Claude…` · `Generated with Claude Code` 를 넣지 않는다', []],
  ['fix(x): 고침\n\nCo-Authored-By: 홍길동 <hong@example.com>', []],
  ['docs: 줄 가운데 Co-Authored-By: Claude 라고 적어도 꼬리말이 아님', []],
  ['본문\n```\nCo-Authored-By: Claude <noreply@anthropic.com>\n```', []],
  ['', []],
];
for(const [text, want] of cases){
  const got = findAttribution(text);
  const ok = JSON.stringify(got) === JSON.stringify(want);
  chk(ok, `${JSON.stringify(text).slice(0, 70)} → ${want.join(' · ') || '없음'}` + (ok ? '' : ' — 실제 ' + (got.join(' · ') || '없음')));
}
say('mutation test — git log -z 읽기');
const z = parseGitLogZ('aaa111\nfix(x): 하나\n\n- a.js: 내용\n\0\nbbb222\nfix(y): 둘\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n\0');
chk(z.length === 2 && z[0].sha === 'aaa111' && z[1].sha === 'bbb222', '커밋 둘 · sha 를 첫 줄에서 — 실제 ' + JSON.stringify(z.map((c) => c.sha)));
chk(findAttribution(z[0].message).length === 0 && findAttribution(z[1].message).length === 1, '두 번째 커밋만 걸림(줄 맨 앞 꼬리말이 메시지 첫 줄 뒤에서도 잡힘)');
chk(parseGitLogZ('').length === 0, '빈 출력 → 커밋 0');
say(`통과 ${pass} · 실패 ${fail}`);
process.exit(fail ? 1 : 0);
